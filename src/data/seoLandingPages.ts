export const seoLandingPages: SeoLandingPage[] = rawSeoLandingPages.map((page) => {
  const enhancement = enhancements[page.slug] || {};
  const searchIntents = enhancement.searchIntents || searchIntentMaps[page.slug] || [];
  const links = [...(enhancement.relatedServices || enhancement.links || page.links), ...baseCommercialLinks];
  const faq = mergeFaq([...(enhancement.faq || page.faq), ...buildIntentFaq({ ...page, ...enhancement }, searchIntents)]);

  return {
    ...page,
    ...enhancement,
    searchIntents,
    faq,
    links,
  };
});

