function buildIntentFaq(page: SeoLandingPage, groups: NonNullable<SeoLandingPage['searchIntents']>) {
  return groups.flatMap((group) =>
    group.phrases.map((phrase) => ({
      question: `Можно обратиться, если ${phrase}?`,
      answer: `${group.answer} Это относится к услуге “${page.title}”: сначала уточняем детали, затем согласуем формат, сроки и стоимость.`,
    })),
  );
}

function mergeFaq(items: SeoLandingPage['faq']) {
  const seen = new Set<string>();
  return items.filter((item) => {
    const key = item.question.toLowerCase();
    if (seen.has(key)) return false;
    seen.add(key);
    return true;
  }).slice(0, 50);
}

